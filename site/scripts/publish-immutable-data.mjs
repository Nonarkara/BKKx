// Content-addressed copies of the files the maps fetch at runtime.
//
// Each file in RUNTIME_FILES is copied to /data/v/<sha256-12>/<name> and
// app/data/data-urls.json maps its stable path to that copy. public/_headers
// caches /data/v/* for a year as immutable: a changed file gets a new
// folder, so a cached copy is never stale and a returning visitor makes no
// request at all for unchanged data. Before this, every /data/ file was
// served `max-age=0, must-revalidate`, so each visit re-asked for every file
// through both Workers (the bkk.nonarkara.org edge proxy and bkkx-site).
//
// The stable paths stay exactly where they are — /datasets links to them
// and other people may too. The versioned copies are build output
// (gitignored); data-urls.json is committed and deterministic, so it only
// changes when a data file does.
//
// Idea credited: immutable build folders behind a small no-cache pointer,
// from the Longdo Map 3D team's public write-up of Longdo3D v2 (their 3D
// Tiles builds live in dated folders cached for a year). Here the folder is
// the content hash rather than the date, and the pointer is the JSON baked
// into the hashed client bundle, so it costs no extra round trip. No Longdo
// code is used.
//
// Runs in `npm run build` and `npm run dev` (data:publish).

import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pub = resolve(here, "../public");
const outDir = join(pub, "data/v");
const pointer = resolve(here, "../app/data/data-urls.json");

const RUNTIME_FILES = [
  "/data/bkk-heritage-detail.geojson",
  "/data/bkk-landmarks.geojson",
  "/data/bkk-hero-monuments.geojson",
  "/data/bkk-heritage-forms.json",
  "/data/bangkok-rowhouse-footprint-candidates.geojson",
  "/data/shophouse-pressure.geojson",
  "/data/bkk-land-price.geojson",
  "/data/sukhumvit71-corridor.geojson",
  "/pois/temples.geojson",
  "/pois/royal-temples.geojson",
  "/pois/national-museums.geojson",
  "/pois/national-archives.geojson",
  "/pois/national-libraries.geojson",
];

const hashOf = (buf) => createHash("sha256").update(buf).digest("hex").slice(0, 12);

const files = {};
const keep = new Set();
for (const path of RUNTIME_FILES) {
  const src = join(pub, path);
  if (!existsSync(src)) throw new Error(`publish-immutable-data: ${path} is listed but missing`);
  const hash = hashOf(readFileSync(src));
  const dest = join(outDir, hash, basename(path));
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(src, dest);
  keep.add(hash);
  files[path] = `/data/v/${hash}/${basename(path)}`;
}
// Old builds are local build output only; the deploy carries just the current set.
for (const name of existsSync(outDir) ? readdirSync(outDir) : []) {
  if (!keep.has(name)) rmSync(join(outDir, name), { recursive: true, force: true });
}

const body = {
  note: "Generated by scripts/publish-immutable-data.mjs. Stable path -> content-addressed copy, cached immutable for a year (public/_headers).",
  files,
};
const next = JSON.stringify(body, null, 2) + "\n";
const prev = existsSync(pointer) ? readFileSync(pointer, "utf8") : "";
if (next !== prev) writeFileSync(pointer, next);
console.log(`publish-immutable-data: ${RUNTIME_FILES.length} files -> /data/v/<hash>/ (${next === prev ? "pointer unchanged" : "pointer updated"})`);
